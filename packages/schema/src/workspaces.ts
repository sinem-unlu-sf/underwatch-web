/**
 * Authorized local workspaces (Ask Witness addendum, section 4.5). The backend is the only component that touches
 * local files, and only inside a workspace the user explicitly authorized (or the disposable demo workspace the app
 * creates from a template with synthetic secrets only). Paths in requests are always workspace-relative.
 */
import { z } from "zod";
import { SafeguardId, Timestamp } from "./entities";
import { idPattern } from "./ids";

export const WorkspaceId = z.string().regex(idPattern("workspace"));
export const WorkspaceFileChangeId = z.string().regex(idPattern("workspace_file_change"));
export const SafeguardVersionId = z.string().regex(idPattern("safeguard_version"));

const Sha256Hex = z.string().regex(/^[0-9a-f]{64}$/);
export { Sha256Hex };

/** demo: created by the app under data/workspaces/ from a template, synthetic secrets only. user: a path the user authorized. */
export const WorkspaceKind = z.enum(["demo", "user"]);
export type WorkspaceKind = z.infer<typeof WorkspaceKind>;

/** active: usable. missing: root_path no longer exists / is not a directory. revoked: authorization withdrawn (never written to). */
export const WorkspaceStatus = z.enum(["active", "missing", "revoked"]);
export type WorkspaceStatus = z.infer<typeof WorkspaceStatus>;

export const Workspace = z.object({
  id: WorkspaceId,
  label: z.string().min(1).max(200),
  /** Absolute, realpath-resolved directory. All file access is confined below it (symlinks resolved, no "..", no absolute rel paths). */
  root_path: z.string().min(1),
  kind: WorkspaceKind,
  authorized_at: Timestamp,
  status: WorkspaceStatus,
});
export type Workspace = z.infer<typeof Workspace>;

/**
 * Workspace-relative path the app may read/write. Only CLAUDE.md files are writable in this build:
 * "CLAUDE.md" or "<subdir>/CLAUDE.md" (directory-level). Never absolute, never "..", never a dot-directory like .git/.claude.
 */
export const ClaudeMdRelPath = z
  .string()
  .min(1)
  .max(300)
  .regex(/^(?:[A-Za-z0-9_-][A-Za-z0-9_.-]*\/)*CLAUDE\.md$/, "must be CLAUDE.md or <subdir>/CLAUDE.md (workspace-relative)")
  .refine((p) => !p.split("/").some((seg) => seg === ".." || seg === "."), "must not contain . or .. segments");
export type ClaudeMdRelPath = z.infer<typeof ClaudeMdRelPath>;
export const DEFAULT_CLAUDE_MD_PATH = "CLAUDE.md";

export const WorkspaceFileChangeStatus = z.enum(["applied", "rolled_back"]);
export type WorkspaceFileChangeStatus = z.infer<typeof WorkspaceFileChangeStatus>;

/** One applied file write. before/after content lives in the BlobStore (data/evidence/blobs), referenced by sha256. */
export const WorkspaceFileChange = z.object({
  id: WorkspaceFileChangeId,
  workspace_id: WorkspaceId,
  safeguard_id: SafeguardId,
  version_id: SafeguardVersionId,
  rel_path: z.string().min(1),
  /** Null when the file did not exist before the change. */
  before_sha256: Sha256Hex.nullable(),
  after_sha256: Sha256Hex,
  /** BlobStore ref (sha256) of the full before content; null when the file did not exist. */
  before_blob: Sha256Hex.nullable(),
  after_blob: Sha256Hex,
  status: WorkspaceFileChangeStatus,
  applied_at: Timestamp,
  rolled_back_at: Timestamp.nullable(),
});
export type WorkspaceFileChange = z.infer<typeof WorkspaceFileChange>;

/** Readable before/after for review. Generated by the server from the CURRENT file content at request time. */
export const FileDiffPreview = z.object({
  /** Null when no workspace is connected: the diff is against an empty file and offered as a copyable patch only. */
  workspace_id: WorkspaceId.nullable(),
  rel_path: z.string().min(1),
  before_exists: z.boolean(),
  /** Hash of the content the diff was generated from. The client echoes it back as expected_before_sha256 on approve. */
  before_sha256: Sha256Hex.nullable(),
  after_sha256: Sha256Hex,
  /** Full texts (CLAUDE.md is small; capped at MAX_CLAUDE_MD_BYTES). Untrusted content: render as text, never as HTML/markdown. */
  before: z.string().nullable(),
  after: z.string(),
  unified_diff: z.string(),
  /** Set when an equivalent instruction already exists; the server then proposes no change (after === before). */
  duplicate_of: z.string().nullable(),
  /**
   * Heuristic warnings: existing lines (outside Underwatch blocks) that appear to explicitly ALLOW what the new
   * instruction restricts. Reported for the user to resolve; the server never edits or removes those lines.
   * Optional for compatibility (absent = not checked).
   */
  contradictions: z
    .array(z.object({ line_number: z.number().int().positive(), line: z.string(), reason: z.string() }))
    .optional(),
  generated_at: Timestamp,
});
export type FileDiffPreview = z.infer<typeof FileDiffPreview>;

export const MAX_CLAUDE_MD_BYTES = 256 * 1024;

/**
 * Safeguard instructions are inserted as a marked block so re-versions replace (not duplicate) the block and rollback
 * is exact. Markers are HTML comments: invisible in rendered markdown, ignored by Claude Code as plain text.
 */
export function claudeMdBlockMarkers(safeguardId: string): { begin: string; end: string } {
  return { begin: `<!-- underwatch:safeguard ${safeguardId} BEGIN -->`, end: `<!-- underwatch:safeguard ${safeguardId} END -->` };
}

/** Markers written before the product was renamed to Underwatch; still recognized so existing blocks are replaced, not duplicated. */
export function legacyClaudeMdBlockMarkers(safeguardId: string): { begin: string; end: string } {
  return { begin: `<!-- kernel-witness:safeguard ${safeguardId} BEGIN -->`, end: `<!-- kernel-witness:safeguard ${safeguardId} END -->` };
}

/** Any safeguard block marker, current or legacy. */
export const ANY_CLAUDE_MD_MARKER_RE = /(?:underwatch|kernel-witness):safeguard/;

/** Locates this safeguard's block under the current or the legacy markers. */
function findClaudeMdBlock(text: string, safeguardId: string): { start: number; afterEnd: number } | null {
  for (const { begin, end } of [claudeMdBlockMarkers(safeguardId), legacyClaudeMdBlockMarkers(safeguardId)]) {
    const start = text.indexOf(begin);
    const stop = start === -1 ? -1 : text.indexOf(end, start);
    if (start !== -1 && stop !== -1) return { start, afterEnd: stop + end.length };
  }
  return null;
}

/** Normalizes instruction text for duplicate detection (case/whitespace/markdown bullets insensitive). */
export function normalizeInstruction(text: string): string {
  return text
    .toLowerCase()
    .replace(/^[\s>*\-+\d.)]+/gm, "")
    .replace(/\s+/g, " ")
    .trim();
}

/**
 * Deterministic merge used for diffs, apply, and patch export. Preserves all unrelated content byte-for-byte:
 * - if a block for this safeguard exists, only the text between its markers is replaced;
 * - otherwise the block is appended after one blank line (a trailing newline is added if missing);
 * - before === null (no file) yields just the block.
 * `content` must not contain the marker strings (callers reject such content as validation_error).
 */
export function mergeClaudeMdBlock(before: string | null, safeguardId: string, content: string): string {
  const { begin, end } = claudeMdBlockMarkers(safeguardId);
  const body = content.replace(/\r\n/g, "\n").trim();
  const block = `${begin}\n${body}\n${end}\n`;
  if (before === null || before.length === 0) return block;
  const found = findClaudeMdBlock(before, safeguardId);
  if (found) {
    const rest = before.slice(found.afterEnd).replace(/^\n/, "");
    return before.slice(0, found.start) + block + rest;
  }
  const base = before.endsWith("\n") ? before : `${before}\n`;
  return `${base}\n${block}`;
}

/** Removes this safeguard's block (used to preview rollback; actual rollback restores the stored before blob). */
export function removeClaudeMdBlock(text: string, safeguardId: string): string {
  const found = findClaudeMdBlock(text, safeguardId);
  if (!found) return text;
  let head = text.slice(0, found.start);
  const tail = text.slice(found.afterEnd).replace(/^\n/, "");
  if (head.endsWith("\n\n")) head = head.slice(0, -1);
  return head + tail;
}

